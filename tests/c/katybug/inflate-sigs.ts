import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Prints src/gmux/katybug/inflate-sigs.h: the static x86-64 GNU gzip 1.13 that gzip-build.sh makes, as FNV-1a hashes
 * of the bytes of inflate (whole), fill_inbuf, flush_window and abort_gzip_signal, and the distances from inflate's
 * entry to those functions and to the globals inflate and fill_inbuf use. It also prints the prim.c row for the CRC
 * loop flush_window carries (updcrc, inlined).
 * `node --experimental-strip-types tests/c/katybug/inflate-sigs.ts <gzip> <gzip.dbg> [llvm bin dir]`
 */
const [path, dbg, llvm = process.env.LLVM ?? '/opt/homebrew/opt/llvm/bin'] = process.argv.slice(2);
if (!path || !dbg) {
	console.error('usage: inflate-sigs.ts <gzip> <gzip.dbg> [llvm bin dir]');
	process.exit(2);
}
const file = readFileSync(path);
const TEXT = 0x400000;

const symbols = new Map<string, { at: number; size: number }>();
for (const line of execFileSync(join(llvm, 'llvm-nm'), ['-S', dbg]).toString().split('\n')) {
	const m = /^([0-9a-f]+) ([0-9a-f]+) [a-zA-Z] (\w+)$/.exec(line);
	if (m) symbols.set(m[3], { at: parseInt(m[1], 16), size: parseInt(m[2], 16) });
}
const sym = (name: string) => {
	const s = symbols.get(name);
	if (!s) throw new Error(`no symbol ${name}`);
	return s;
};

const fnv = (b: Buffer): bigint => {
	let h = 0xcbf29ce484222325n;
	for (const x of b) h = ((h ^ BigInt(x)) * 0x100000001b3n) & 0xffffffffffffffffn;
	return h;
};
const hex = (v: bigint) => `0x${v.toString(16).padStart(16, '0')}ull`;
const bytes = (start: number, n: number) => file.subarray(start - TEXT, start - TEXT + n);
const region = (name: string) => {
	const s = sym(name);
	const b = bytes(s.at, s.size);
	return { at: s.at, len: s.size, head: hex(b.readBigUInt64LE(0)), hash: hex(fnv(b)), bytes: b };
};

const entry = sym('inflate').at;
const rel = (name: string) => sym(name).at - entry;
const inflate = region('inflate');
const fill = region('fill_inbuf');
const flush = region('flush_window');
const handler = region('abort_gzip_signal');

const pattern = Buffer.from('0fb60a4883c20131c148c1e8080fb6c9493304c84839f275e7', 'hex');
const at = flush.bytes.indexOf(pattern);
if (at < 0) throw new Error('the crc loop is not in flush_window');
const crcRow = `{KB_X86, P_GZCRC, ${pattern.length}, ${hex(pattern.readBigUInt64LE(0))}, ${hex(fnv(pattern))}},`;

const row = [
	`${inflate.len}, ${inflate.head}, ${inflate.hash},`,
	`${rel('fill_inbuf')}, ${fill.len}, ${fill.head}, ${fill.hash},`,
	`${rel('flush_window')}, ${flush.len}, ${flush.head}, ${flush.hash},`,
	`${rel('abort_gzip_signal')}, ${handler.len}, ${handler.head}, ${handler.hash},`,
	`${rel('inptr')}, ${rel('insize')}, ${rel('inbuf')}, ${rel('ifd')}, ${rel('window')}, ${rel('outcnt')}, ${rel('bk')}, ${rel('bb')}`
].join('\n');
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../../src/gmux/katybug/inflate-sigs.h');
writeFileSync(
	out,
	`/* generated by tests/c/katybug/inflate-sigs.ts: the static x86-64 GNU gzip 1.13 (Alpine 3.20, gcc -O2) */\n${row}\n`
);
execFileSync('bash', [join(here, '../../../format.sh'), out], { stdio: 'inherit' });
console.error(`wrote ${out}\nprim.c row for the crc loop (flush_window + ${at}): ${crcRow}`);
